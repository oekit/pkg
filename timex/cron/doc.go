// Package cron 提供 Cron 表达式解析和调度功能。
//
// 支持标准 5 字段 Cron 表达式：分 时 日 月 周
//
// ⚠️ 与标准 cron 的方言差异（[#186]）：dow 支持 7≡Sunday；不支持 MON/JAN
// 名字、不支持 L/W/# 扩展；不可满足表达式（2 月 31 日）Next 返回零值
// time.Time 而非报错——从系统 crontab 迁移时注意。
//
// # 夏令时
//
// Next 的返回值**保证严格晚于入参**（零值除外）。调度器最常见的消费形态
//
//	for { next := sched.Next(prev); time.Sleep(time.Until(next)); prev = next }
//
// 一旦 Next 返回不晚于入参的时刻就变成原地热转、任务被疯狂重复执行且永不
// 前进——所以这不是「精度」问题而是**活性**问题（[#214]）。内部推进全部走
// 绝对时间加法、不按墙钟重建，因此：
//
//   - **回拨**（同一墙钟出现两次）：两次出现都会各自被推进到，不会倒退；
//   - **前跳**（某个墙钟不存在，如 America/Santiago 2026-09-06 的 00:00）：
//     目标日/月的起点取该日**最早存在的时刻**；若表达式要求的墙钟时刻当天
//     确实不存在（如「仅在 9/6 00:00」），则该次不触发——与「按墙钟语义
//     该时刻当天不存在」一致，不会无限搜索。
